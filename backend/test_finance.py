"""
财务智能体真实调用测试脚本。

用途：
- 用一段完全虚构的财务文本，检验财务智能体能否识别“增收不增现金、
  高负债、应收账款和存货激增”等风险；
- 直接调用 agents/finance_agent.py 中的 analyze_finance 函数；
- 将模型返回的 Markdown 分析结果打印到终端。

注意：
- 本脚本会真实调用 DeepSeek API，因此会产生少量调用费用；
- 示例公司、年份和所有金额都是虚构的，不对应任何真实企业；
- API Key 仍由 finance_agent.py 从环境变量读取，脚本中不保存任何密钥。
"""

from agents.finance_agent import FinanceAgentError, analyze_finance


# 故意构造一组互相矛盾的虚构财务数据：
# 营业收入、净利润都在增长，但经营现金流大幅下降，负债率高企，
# 应收账款和存货也同时激增。用来看模型能否看穿“表面增长”。
FAKE_FINANCE_TEXT = """
星海智能装备有限公司（虚构案例，仅用于系统测试，所有数据均不真实）

2023 年度：
营业收入 10.10 亿元，营业成本 7.24 亿元，净利润 1.02 亿元，
毛利率 28.3%，净利率 10.1%。经营活动产生的现金流量净额 1.86 亿元。
2023 年末资产负债率 68.5%，流动比率 1.12，应收账款 2.00 亿元，
存货 2.10 亿元。

2024 年度：
营业收入 12.60 亿元，同比增长 24.8%；营业成本 9.78 亿元，
净利润 1.15 亿元，同比增长 12.7%；毛利率 22.4%，净利率 9.1%。
经营活动产生的现金流量净额 0.32 亿元，同比下降 82.8%。
2024 年末资产负债率 85.2%，较上年末上升 16.7 个百分点；
流动比率 0.75；短期借款 7.80 亿元，货币资金 1.10 亿元。
应收账款 4.60 亿元，同比增长 130.0%；存货 3.90 亿元，
同比增长 85.7%。

公司解释：
收入增长主要来自新客户订单增加，但客户回款周期有所延长；
存货增加主要是为下一年度订单提前备货。
""".strip()


def main() -> int:
    """
    执行一次真实的财务分析，并打印结果。

    返回：
        int: 0 表示调用成功；1 表示调用失败。
    """
    print("=" * 72)
    print("财务智能体测试")
    print("=" * 72)
    print("测试资料：虚构公司，营收增长但经营现金流大幅下降，资产负债率 85%")
    print("正在调用 DeepSeek，请稍候……")
    print("-" * 72)

    try:
        # 这一步会真实访问 DeepSeek API，可能等待几十秒。
        result = analyze_finance(FAKE_FINANCE_TEXT)
    except FinanceAgentError as exc:
        # API Key、网络、余额、限流等可预期错误会在这里显示中文原因。
        print("分析失败：", str(exc))
        return 1
    except Exception as exc:
        # 捕获未预期异常，避免终端只显示一长串英文堆栈信息。
        # 这里只打印异常类型和简短原因，不涉及任何密钥内容。
        print("发生未预期错误：", type(exc).__name__, str(exc))
        return 1

    # 输出模型生成的分析结果；资料不完整时，这里会显示固定缺失提示。
    print("分析结果：")
    print()
    print(result)
    print()
    print("=" * 72)
    print("测试调用完成")
    print("=" * 72)
    return 0


if __name__ == "__main__":
    # 只有直接运行本文件时才执行 API 调用；
    # 被其他程序 import 时不会自动产生费用。
    raise SystemExit(main())
