def _normalize_dimensions(
    dimensions: Sequence[str] | None,
) -> list[str]:
    """
    校验并整理用户选择的分析维度。

    参数：
        dimensions: 用户选择的维度名称。传入 None 时表示默认全选。

    返回：
        list[str]: 按系统固定顺序排好、去重后的维度列表。

    异常：
        FinanceAgentError: 未选择任何维度，或包含不支持的维度名称时抛出。
    """
    # 不传维度时保持旧行为：默认分析全部五个维度。
    if dimensions is None:
        return list(AVAILABLE_DIMENSIONS)

    # 防止调用方误传单个字符串，否则 Python 会把字符串拆成一个个字符。
    if isinstance(dimensions, str):
        requested_dimensions = [dimensions]
    else:
        requested_dimensions = list(dimensions)

    # 检查是否有网页选项之外的值，避免模型收到无法识别的维度名称。
    unknown_dimensions = [
        name for name in requested_dimensions
        if name not in AVAILABLE_DIMENSIONS
    ]
    if unknown_dimensions:
        raise FinanceAgentError(
            "存在不支持的分析维度：" + "、".join(unknown_dimensions)
        )

    # 使用集合去重，再按系统固定顺序重排，
    # 保证无论用户按什么顺序勾选，报告顺序都稳定一致。
    requested_set = set(requested_dimensions)
    ordered_dimensions = [
        name for name in AVAILABLE_DIMENSIONS if name in requested_set
    ]

    if not ordered_dimensions:
        raise FinanceAgentError("请至少选择一个分析维度。")

    return ordered_dimensions


